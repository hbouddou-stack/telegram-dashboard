import re

with open('handlers/support.py', 'r', encoding='utf-8') as f:
    content = f.read()

start_pattern = r'unread_count = await db\.get_unread_reports_count\(user_id\)'
end_pattern = r'@router\.callback_query\(F\.data == "support_report_menu"\)'

match = re.search(f'({start_pattern}.*?)({end_pattern})', content, re.DOTALL)
if match:
    new_code = '''
    text = (
        "?? <b>?????? ?? ?? ???? ????? ????? ??????????</b>\\n\\n"
        "??? ?????? ??????? ??????\\n"
        "<i>(???? ?????? ???????? ????????? ?? ???????? ??? ?????? ?????? ???????? ?????)</i>"
    )
    
    if isinstance(event, CallbackQuery):
        await event.message.edit_text(text, parse_mode="HTML")
    else:
        await event.answer(text, parse_mode="HTML")

'''
    # We replace everything from unread_count until the next router callback
    content = content[:match.start()] + new_code + match.group(2) + content[match.end():]
    with open('handlers/support.py', 'w', encoding='utf-8') as f:
        f.write(content)
    print("Success")
else:
    print("Match not found")
